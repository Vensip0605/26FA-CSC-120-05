#include <iostream>
using namespace std;

int main()
{

    int a = 5, b = 8;

    cout << (a < b) << endl;  // prints 1 (true)
    cout << (a == b) << endl; // prints 0 (false)

    string name = "Nathan";
    cout << (name == "nathan") << endl;
    cout << (name != "nathan") << endl;

    return 0;
}
